"""Build js/spelling/woc2024.js from the official "Words of the Champions" PDF.

Usage:
  python3 -m venv .venv && .venv/bin/pip install pypdf
  .venv/bin/python tools/build-woc.py "path/to/2024 Words of the Champions.pdf"

PDF: https://spellingbee.com/sites/default/files/inline-files/2024%20Words%20of%20the%20Champions.pdf
"""
import json, re, sys, unicodedata
from pathlib import Path
from pypdf import PdfReader

OUT = Path(__file__).resolve().parent.parent / 'js' / 'spelling' / 'woc2024.js'
# 0-based page ranges: [study list pages, Words of the Champions pages]
LEVELS = [
    ('one', 'One Bee', '1️⃣', range(3, 5), range(5, 13)),
    ('two', 'Two Bee', '2️⃣', range(13, 15), range(15, 29)),
    ('three', 'Three Bee', '3️⃣', range(29, 31), range(31, 39)),
]
VOCAB_PAGES = range(43, 50)
POS = r'(plural noun|noun|verb|adjective|adverb|interjection|preposition|conjunction|pronoun)'
DEF_START = re.compile(rf'^{POS}\s*[–-]')
ENTRY = re.compile(r"^[A-Za-zÀ-ÿ][A-Za-zÀ-ÿ'’\-.]*( [A-Za-zÀ-ÿ'’\-.]+){0,4}\**$")
HEADER = re.compile(r'difficulty level|words of the champions|school spelling bee study list', re.I)
# Fun-fact box headings that look like words (the box text that follows is a full sentence).
HEADING_LEAD = ('a', 'the', 'our', 'in', 'from', 'who', 'did', 'find')


def nwords(s):
    return len(s.split())


def clean(s):
    return s.replace('*', '').replace('’', "'").strip()


def parse(lines):
    """Return [{'w', 'alts'}] from page lines, skipping margin definitions and fun-fact boxes."""
    lines = [l.strip() for l in lines if l.strip()]
    entries, in_def = [], False
    for i, s in enumerate(lines):
        nxt = lines[i + 1] if i + 1 < len(lines) else ''
        if in_def:
            in_def = not s.endswith('.')
            continue
        if DEF_START.match(s):
            in_def = not s.endswith('.')
            continue
        if re.fullmatch(r'\d+|[A-Z]', s) or HEADER.search(s):
            continue
        m = re.match(r'^OR (.+)$', s)
        if m:
            entries[-1]['alts'].append(clean(m.group(1)))
            continue
        if not ENTRY.match(s) or s.endswith('.') or '. ' in s:
            continue
        # A short phrase right before a full sentence is a fun-fact heading, not a word.
        # Headings can wrap: "a big-time" / "Spellebrity", so drop the lead-in line too.
        lead_before = bool(entries) and entries[-1]['lead']
        if nwords(nxt) >= 6 and (nwords(s) > 1 or lead_before):
            if lead_before:
                entries.pop()
            continue
        entries.append({'w': clean(s), 'alts': [], 'lead': nwords(s) > 1 and s.split()[0] in HEADING_LEAD})
    return [{'w': e['w'], 'alts': e['alts']} for e in entries]


def vocab_definitions(pages):
    text = '\n'.join(pages[i] for i in VOCAB_PAGES)
    defs = {}
    for m in re.finditer(r'^(\S[^–\n]*?) – ([a-z ]+) – (.+?\.)\s*$(?:\n\s{6,}(.+?)$)?', text, re.M):
        d = m.group(3) + (' ' + m.group(4).strip() if m.group(4) else '')
        defs[clean(m.group(1)).lower()] = (m.group(2).strip(), re.sub(r'\s+', ' ', d))
    return defs


def main(pdf):
    pages = [p.extract_text() or '' for p in PdfReader(pdf).pages]
    defs = vocab_definitions(pages)
    seen, lists = set(), []
    for key, name, emoji, study, champs in LEVELS:
        for part, rng, title in (('study', study, 'School Study List'), ('champions', champs, 'Words of the Champions')):
            words = []
            for e in parse([l for i in rng for l in pages[i].split('\n')]):
                k = unicodedata.normalize('NFC', e['w']).lower()
                if k in seen:
                    continue
                seen.add(k)
                pos, d = defs.get(k, ('', ''))
                words.append({'w': e['w'], **({'alts': e['alts']} if e['alts'] else {}), **({'pos': pos, 'def': d} if d else {})})
            lists.append({'id': f'woc24-{key}-{part}', 'name': f'{name} - {title}', 'emoji': emoji, 'group': '2024 Words of the Champions', 'words': words})
    total = sum(len(l['words']) for l in lists)
    body = ',\n'.join('  ' + json.dumps(l, ensure_ascii=False) for l in lists)
    OUT.write_text(
        '// AUTO-GENERATED by tools/build-woc.py from the official Scripps "2024 Words of the Champions" PDF. Do not edit.\n'
        f'// {total} words in {len(lists)} lists.\n'
        f'export const WOC_2024 = [\n{body},\n];\n')
    for l in lists:
        print(f"{l['name']}: {len(l['words'])}")
    print('total', total, '->', OUT)


if __name__ == '__main__':
    main(sys.argv[1])
